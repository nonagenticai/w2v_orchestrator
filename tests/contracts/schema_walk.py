"""Dotted-leaf walker over the vendored compiler CompileRequest JSON Schema.

The point of this module is to make TWO very different things — a JSON Schema
document and an actual emitted payload — comparable as flat sets of dotted
strings. That symmetry is the whole mechanism: once both sides are
``frozenset[str]``, the two directions of contract drift are plain set algebra.

* ``payload_leaves(payload).leaves - schema_leaves(...)`` → the orchestrator
  invented a field the compiler does not declare (what ``extra="forbid"`` used
  to catch).
* ``schema_leaves(...) - <union of emitted leaves>`` → the compiler grew a knob
  NO producer sets, i.e. a silently inert field (what ``extra="forbid"`` could
  never catch, and the failure mode this project keeps re-shipping).

Worked example
--------------
Schema fragment::

    {"properties": {"shots": {"items": {"$ref": "#/$defs/Shot"}, "type": "array"}},
     "$defs": {"Shot": {"properties": {"id": {"type": "string"},
                                       "sfx": {"items": {"$ref": "#/$defs/Cue"},
                                               "type": "array"}}},
               "Cue":  {"properties": {"gain_db": {"type": "number"}}}}}

``schema_leaves`` →  ``{"shots.id", "shots.sfx.gain_db"}``

Payload::

    {"shots": [{"id": "s1", "sfx": [{"gain_db": -3.0}, {"gain_db": 0.0}]}]}

``payload_leaves(...).leaves`` →  ``{"shots.id", "shots.sfx.gain_db"}``
(and ``.scalar_leaves`` is the same set here — every one of those positions
held a genuine ``str``/``float``, not an early stop.)

List nesting is COLLAPSED on both sides (``shots[0].sfx[1].gain_db`` and
``shots[3].sfx[0].gain_db`` are the same contract position), which is what makes
the two walks line up.

Stdlib only, deliberately: ``jsonschema`` / ``datamodel-code-generator`` are not
dependencies of this repo and adding one to run a test-only walk is not worth a
lockfile cascade across 13 consumers.
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
from typing import NamedTuple

# The vendored artifact lives next to this module. It is GENERATED by
# ``video_compiler_service/scripts/regen_contract_artifact.py`` from
# ``CompileRequest.model_json_schema()`` with ``sort_keys=True`` — refresh it by
# copying that file over, never by hand-editing.
ARTIFACT_PATH: Path = Path(__file__).with_name("compile_request.schema.json")

_REF_PREFIX = "#/$defs/"


def as_mapping(value: object) -> dict[str, object] | None:
    """Narrow an arbitrary JSON value to a str-keyed mapping.

    ``isinstance(value, Mapping)`` only narrows to ``Mapping[Unknown, object]``,
    and ``Mapping`` is invariant in its key type, so the result is not usable
    where ``Mapping[str, object]`` is required. Rebuilding the dict makes the
    key type a fact instead of an assumption.
    """
    if not isinstance(value, Mapping):
        return None
    return {str(key): item for key, item in value.items()}


def load_schema() -> dict[str, object]:
    """Read + parse the vendored CompileRequest JSON Schema artifact."""
    raw = ARTIFACT_PATH.read_text(encoding="utf-8")
    parsed = json.loads(raw)
    if not isinstance(parsed, dict):  # pragma: no cover - artifact is an object
        raise TypeError(f"{ARTIFACT_PATH} is not a JSON object")
    return parsed


# --------------------------------------------------------------------------- #
# schema side
# --------------------------------------------------------------------------- #
def schema_leaves(schema: Mapping[str, object]) -> frozenset[str]:
    """Every declared leaf position of the schema as a dotted path.

    A "leaf" is a schema node with no further declared object structure: no
    ``properties`` to descend into and no ``items``/``$ref``/``anyOf`` that
    would lead to some. Scalars, enums, tuple-shaped ``prefixItems`` (e.g. a
    ``bbox`` 4-tuple) and free-form mappings all land here.
    """
    defs: dict[str, object] = as_mapping(schema.get("$defs")) or {}
    out: set[str] = set()
    _walk_schema(dict(schema), "", defs, frozenset(), out)
    return frozenset(out)


def _walk_schema(
    node: dict[str, object],
    path: str,
    defs: dict[str, object],
    visiting: frozenset[str],
    out: set[str],
) -> None:
    # --- $ref resolution, cycle-safe ---------------------------------------
    ref = node.get("$ref")
    if isinstance(ref, str):
        _walk_ref(ref, path, defs, visiting, out)
        return

    # --- union keywords -----------------------------------------------------
    # ``Foo | None`` is emitted by pydantic as
    # ``anyOf: [{$ref: Foo}, {type: "null"}]``. We MUST descend into the Foo
    # branch, otherwise every optional sub-model in the request (music, finish,
    # mastering, every optional Shot block) collapses to a single leaf and the
    # inert-knob direction goes blind. The null branch carries no fields and is
    # skipped so it cannot turn an object position into a bogus scalar leaf.
    branches = _union_branches(node)
    if branches is not None:
        descended = False
        for branch in branches:
            if _is_null_schema(branch):
                continue
            _walk_schema(branch, path, defs, visiting, out)
            descended = True
        if not descended:  # pragma: no cover - a union of nothing but null
            _emit(path, out)
        return

    # --- arrays -------------------------------------------------------------
    # List nesting is COLLAPSED: the element schema is walked at the SAME dotted
    # path as the array itself, so ``shots`` + ``Shot.id`` → ``shots.id``.
    # ``prefixItems`` (fixed tuples such as a bbox) is deliberately NOT followed:
    # positional tuple members are not named contract positions.
    items = as_mapping(node.get("items"))
    if items is not None:
        _walk_schema(items, path, defs, visiting, out)
        return

    # --- objects ------------------------------------------------------------
    properties = as_mapping(node.get("properties"))
    if properties:
        for prop_name, prop_schema in properties.items():
            child_path = f"{path}.{prop_name}" if path else str(prop_name)
            prop_node = as_mapping(prop_schema)
            if prop_node is not None:
                _walk_schema(prop_node, child_path, defs, visiting, out)
            else:  # pragma: no cover - malformed schema
                _emit(child_path, out)
        return

    # --- leaf ---------------------------------------------------------------
    # Everything else is a leaf. This deliberately includes a free-form mapping
    # (``dict[str, str]`` / ``dict[str, Any]``, emitted as ``type: object`` with
    # an ``additionalProperties`` schema and no ``properties``): its KEYS are
    # data, not contract positions, so descending would invent leaves that can
    # never appear in the schema. ``tags`` is the live example. Payload-side
    # descent past such a leaf is absorbed by the ancestor rule in
    # ``unknown_leaves``.
    _emit(path, out)


def _walk_ref(
    ref: str,
    path: str,
    defs: dict[str, object],
    visiting: frozenset[str],
    out: set[str],
) -> None:
    """Expand a ``$ref`` at *path*, stopping on a cycle or a dangling target.

    ``visiting`` holds the $def names already open ON THIS PATH, so a model that
    references itself (directly or through a chain) stops instead of recursing
    forever. It is per-path, not global: the same $def reached down two different
    branches must still expand under each branch.
    """
    if not ref.startswith(_REF_PREFIX):  # pragma: no cover - pydantic only emits $defs refs
        _emit(path, out)
        return
    name = ref[len(_REF_PREFIX) :]
    target = as_mapping(defs.get(name))
    # Cycle, or a dangling ref: the position exists but expanding adds nothing.
    if name in visiting or target is None:
        _emit(path, out)
        return
    _walk_schema(target, path, defs, visiting | {name}, out)


def _emit(path: str, out: set[str]) -> None:
    if path:
        out.add(path)


def _union_branches(node: dict[str, object]) -> list[dict[str, object]] | None:
    """Return the sub-schemas of an ``anyOf``/``oneOf``/``allOf`` node, if any."""
    for key in ("anyOf", "oneOf", "allOf"):
        raw = node.get(key)
        if isinstance(raw, Sequence) and not isinstance(raw, str | bytes):
            branches = [m for b in raw if (m := as_mapping(b)) is not None]
            if branches:
                return branches
    return None


def _is_null_schema(node: dict[str, object]) -> bool:
    return node.get("type") == "null"


# --------------------------------------------------------------------------- #
# payload side
# --------------------------------------------------------------------------- #
class PayloadWalk(NamedTuple):
    """The result of walking an emitted payload.

    ``leaves`` is every dotted position the payload occupies. ``scalar_leaves``
    is the SUBSET of those that carried a genuine scalar (``str``/``int``/
    ``float``/``bool``).

    Why the split exists at all: acceptance rule 3 in :func:`unknown_leaves`
    ("the path is an ancestor of a declared leaf") legitimately lets a producer
    STOP EARLY — emitting ``music: None`` where the schema declares
    ``music.url``. Applied to the bare path it also accepts a SCALAR AT AN
    OBJECT POSITION, e.g. ``{"shots": [{"audio": "garbage-string"}]}`` where
    ``audio`` must be a ``ShotAudio`` object: ``shots.audio.gain_db`` starts
    with ``shots.audio.``, so the garbage string rides through unflagged. The
    hand-written pydantic mirror this walker replaced caught that; a naive
    ancestor rule does not, so the walk records WHICH leaves came from a scalar
    and the rule refuses those.

    ``None``, ``{}`` and ``[]`` are early stops, NOT scalars — they are exactly
    the legitimate "producer has nothing to say here" case rule 3 serves.

    Pinned by the paired tests ``test_guard_rejects_scalar_where_the_schema_
    declares_an_object`` and ``test_guard_accepts_a_producer_stopping_early_at_
    none``. A change that makes either pass by breaking the other has fixed
    nothing.
    """

    leaves: frozenset[str]
    scalar_leaves: frozenset[str]


def payload_leaves(payload: object) -> PayloadWalk:
    """Every position an actual emitted payload occupies, as a dotted path.

    Same path shape as :func:`schema_leaves`: dict values recurse under
    ``parent.child``, list elements recurse at the SAME path (collapsed), and
    anything else is a leaf. Returns a :class:`PayloadWalk` so callers can tell
    a scalar leaf from an early stop — see that class for why that matters.
    """
    out: set[str] = set()
    scalars: set[str] = set()
    _walk_payload(payload, "", out, scalars)
    return PayloadWalk(frozenset(out), frozenset(scalars))


def _walk_payload(value: object, path: str, out: set[str], scalars: set[str]) -> None:
    if isinstance(value, Mapping):
        # An EMPTY mapping stops here: it carries no field information, and
        # recording the position itself keeps the subset check honest (the
        # ancestor/descendant rules in ``unknown_leaves`` accept it). NOT marked
        # scalar — an empty object is a legitimate early stop, not a type error.
        if not value:
            _emit(path, out)
            return
        for key, sub in value.items():
            child_path = f"{path}.{key}" if path else str(key)
            _walk_payload(sub, child_path, out, scalars)
        return
    if isinstance(value, list | tuple):
        # Collapsed exactly like the schema side; an empty list is a position
        # (again, an early stop rather than a scalar).
        if not value:
            _emit(path, out)
            return
        for item in value:
            _walk_payload(item, path, out, scalars)
        return
    # Scalars — including ``None``, which marks a position the producer touched
    # but left empty. Note str/bytes are intentionally NOT treated as sequences.
    _emit(path, out)
    # Only a GENUINE scalar is recorded as such. ``None`` is deliberately
    # excluded: it is the early stop rule 3 exists for.
    if isinstance(value, str | int | float | bool):
        _emit(path, scalars)


# --------------------------------------------------------------------------- #
# comparison
# --------------------------------------------------------------------------- #
def unknown_leaves(
    emitted: Iterable[str],
    known: frozenset[str],
    *,
    scalar_leaves: frozenset[str] = frozenset(),
) -> frozenset[str]:
    """Emitted paths the schema does not account for.

    A path counts as accounted-for when any of these hold:

    1. It is declared verbatim.
    2. An ANCESTOR of it is a declared leaf — the producer descended into a
       free-form mapping (``tags.master_lufs`` under the leaf ``tags``).
    3. It is an ancestor of a declared leaf AND IS NOT A SCALAR — the producer
       stopped early with ``None`` or an empty container (``music`` where
       ``music.url`` exists).

    Pass ``scalar_leaves`` (from :attr:`PayloadWalk.scalar_leaves`) to arm the
    ``not is_scalar`` guard in rule 3. Without it every path is treated as a
    non-scalar early stop, so a scalar sitting at an object position is
    ACCEPTED — the exact narrowing that would make this walker weaker than the
    pydantic mirror it replaced. The default is empty only so schema-side
    callers, which have no payload values at all, can omit it.

    Anything left over is a field the orchestrator invented; the compiler's own
    request model is ``extra="ignore"``, so live it would be silently DROPPED
    rather than 422'd. That silence is why this check exists.
    """
    return frozenset(
        path for path in emitted if not _is_known(path, known, is_scalar=path in scalar_leaves)
    )


def structure_violations(walk: PayloadWalk, known: frozenset[str]) -> frozenset[str]:
    """Emitted SCALARS sitting where the schema declares further structure.

    These are the paths rule 3 of :func:`unknown_leaves` would wave through if
    it ignored the value's type: ``shots.audio`` holding ``"garbage-string"``
    when the schema declares ``shots.audio.gain_db``/``.mute``/``.fade_*``. It
    is a TYPE error, not an invented field, and callers report it separately —
    calling it "a field the compiler does not declare" sends the reader hunting
    for a typo that is not there.

    Rules 1 and 2 are honoured first, so the result is always a SUBSET of
    ``unknown_leaves(...)`` and a caller can safely compute
    ``invented = unknown - structural``: a scalar at a position the schema
    declares verbatim (or under a free-form mapping leaf) is perfectly valid
    and must not be reported here.
    """
    return frozenset(
        path
        for path in walk.scalar_leaves
        if not _is_declared_or_under_freeform(path, known) and _is_ancestor_of_declared(path, known)
    )


def _is_known(path: str, known: frozenset[str], *, is_scalar: bool) -> bool:
    if _is_declared_or_under_freeform(path, known):
        return True
    # rule 3: path is an ancestor of some declared leaf — a producer stopping
    # early. The ``not is_scalar`` guard is the whole point: an early stop is
    # ``None``/``{}``/``[]``, never a bare str/int/float/bool. Do NOT
    # "simplify" this back to a plain prefix test — that silently re-narrows
    # the guard to less than the pydantic mirror it replaced, and
    # ``test_guard_rejects_scalar_where_the_schema_declares_an_object`` exists
    # to fail when someone does.
    return not is_scalar and _is_ancestor_of_declared(path, known)


def _is_declared_or_under_freeform(path: str, known: frozenset[str]) -> bool:
    """Rules 1 and 2: declared verbatim, or below a declared free-form leaf."""
    if path in known:
        return True
    # rule 2: some ancestor is a declared leaf
    head = path
    while "." in head:
        head = head.rsplit(".", 1)[0]
        if head in known:
            return True
    return False


def _is_ancestor_of_declared(path: str, known: frozenset[str]) -> bool:
    """Whether the schema declares named sub-fields BELOW *path*."""
    prefix = f"{path}."
    return any(candidate.startswith(prefix) for candidate in known)
